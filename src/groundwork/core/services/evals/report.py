"""The eval report: markdown and JSON, deterministic, with no timestamp.

`evals/report.md` and `evals/results/<pack>.json` are generated, never edited: the same
recorded runs give the same bytes, so a diff shows only what changed, and `--check-report`
fails when a committed file differs from a regeneration.
"""

import json
from collections.abc import Sequence
from pathlib import Path

from groundwork.core.domain.evals import CaseResult, PackResult

REPORT_FILE = "report.md"
RESULTS_DIR = "results"
HEADER = "Generated by `groundwork evals`. Do not edit."
HONESTY = (
    "The clients, contacts, rules and emails are synthetic (docs/security.md). Every number "
    "comes from recorded runs of the real agent and judge, replayed offline; regenerate with "
    "`groundwork evals --write-report`."
)


def render_report(results: Sequence[PackResult]) -> str:
    lines = ["# Evals report", "", HEADER, "", HONESTY, "", "## Summary", ""]
    lines += ["| Pack | Cases | Result |", "|---|---|---|"]
    lines += [f"| {r.pack} | {r.metrics.cases} | {_verdict(r)} |" for r in results]
    for result in results:
        lines += _pack_section(result)
    return "\n".join(lines).rstrip() + "\n"


def result_json(result: PackResult) -> str:
    return (
        json.dumps(result.model_dump(mode="json"), sort_keys=True, indent=2, ensure_ascii=False)
        + "\n"
    )


def write_outputs(results: Sequence[PackResult], evals_dir: Path) -> list[Path]:
    """Write the report and one results file per pack. Returns the paths written."""
    (evals_dir / RESULTS_DIR).mkdir(parents=True, exist_ok=True)
    written = [evals_dir / REPORT_FILE]
    written[0].write_text(render_report(results), encoding="utf-8")
    for result in results:
        path = evals_dir / RESULTS_DIR / f"{result.pack}.json"
        path.write_text(result_json(result), encoding="utf-8")
        written.append(path)
    return written


def report_drift(results: Sequence[PackResult], evals_dir: Path) -> list[str]:
    """Every committed file that differs from a regeneration, or is missing."""
    expected = {evals_dir / REPORT_FILE: render_report(results)}
    expected |= {evals_dir / RESULTS_DIR / f"{r.pack}.json": result_json(r) for r in results}
    problems = []
    for path, text in expected.items():
        if not path.is_file():
            problems.append(f"{path} is missing")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"{path} differs from a replay regeneration")
    return problems


def _verdict(result: PackResult) -> str:
    failed = [t.scorer for t in result.thresholds if not t.passed]
    return "PASS" if not failed else "FAIL (" + ", ".join(failed) + ")"


def _pack_section(result: PackResult) -> list[str]:
    m = result.metrics
    lines = [
        "",
        f"## {result.pack}",
        "",
        f"Result: **{_verdict(result)}**",
        "",
        "### Thresholds",
        "",
    ]
    lines += ["| Scorer | Value | Threshold | Result |", "|---|---|---|---|"]
    for t in result.thresholds:
        value = (
            "not measured"
            if t.value is None
            else f"{t.value:g}"
            if t.value == int(t.value)
            else f"{t.value:.2f}"
        )
        state = "skipped" if t.value is None else "pass" if t.passed else "FAIL"
        lines.append(f"| {t.scorer} | {value} | {t.threshold:g} | {state} |")
    lines += ["", "### Before and after the agent", ""]
    lines += ["| | Raw draft | Harmonized |", "|---|---|---|"]
    lines += [
        f"| False claims | {m.raw_false_claims} | {m.fact_false_claims} |",
        f"| Forbidden-pattern hits | {m.raw_forbidden_hits} | {_forbidden_total(result)} |",
        f"| Tone, mean from 1 to 5 | {m.raw_tone_mean:.2f} | {m.tone_mean:.2f} |",
    ]
    lines += ["", "### Cases", ""]
    columns = [
        "Case",
        "Tags",
        "Channel",
        "Route (expected / decided)",
        "False claims",
        "Missing",
        "Forbidden",
        "Tone",
        "Rule violations",
    ]
    lines += ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += [_case_row(c) for c in result.cases]
    a = result.agreement
    lines += ["", "### Judge calibration", ""]
    differences = ", ".join(map(str, a.differences)) or "none"
    lines.append(
        f"The judge is within one point of the human label on {a.agree} of {a.total} cases "
        f"(differences: {differences})."
    )
    if result.retrieval:
        r = result.retrieval
        lines += [
            "",
            "### Retrieval",
            "",
            f"recall@{r.k}: {r.found} of {r.total} questions found their passage.",
        ]
        lines += [f"- missed: {q}" for q in r.missed]
    if result.notes:
        lines += ["", "### Notes", ""] + [f"- {n}" for n in result.notes]
    return lines


def _forbidden_total(result: PackResult) -> int:
    return sum(len(c.forbidden_hits) for c in result.cases)


def _case_row(c: CaseResult) -> str:
    route = f"{c.expected_route} / {c.route}"
    route = route if c.routing_ok else f"**{route}**"
    cells = [
        c.id,
        ", ".join(c.tags) or "-",
        c.channel,
        route,
        str(c.facts.false_claims),
        ", ".join(c.facts.missing) or "-",
        "; ".join(c.forbidden_hits) or "-",
        str(c.tone),
        ", ".join(c.rule_violations) or "-",
    ]
    return "| " + " | ".join(x.replace("|", "\\|") for x in cells) + " |"
